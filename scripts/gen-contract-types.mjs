// Generates src/contracts/calc/types.generated.ts from the calc.v1 JSON Schemas
// (src/contracts/calc/*.schema.json, a byte-identical copy of the backend's
// internal/voyagecalc/contract/schema/). Supports exactly the schema subset the
// contract uses: object/properties/required, arrays, enums, nullable type
// arrays, local $defs/$ref and map-style additionalProperties.
//
//   node scripts/gen-contract-types.mjs          # write
//   node scripts/gen-contract-types.mjs --check  # exit 1 if out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/contracts/calc");
const outFile = path.join(dir, "types.generated.ts");
const files = ["calculation-input.v1.schema.json", "calculation-result.v1.schema.json"];

export function generate() {
  const out = [
    "// GENERATED by scripts/gen-contract-types.mjs from the calc.v1 JSON Schemas. Do not edit.",
    "",
  ];
  const emitted = new Set();
  for (const file of files) {
    const schema = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
    const defs = schema.$defs || {};
    out.push(`// ── ${file}`);
    emitInterface(out, schema.title, schema, emitted);
    for (const name of Object.keys(defs)) emitInterface(out, name, defs[name], emitted);
  }
  return out.join("\n") + "\n";
}

function emitInterface(out, name, node, emitted) {
  if (emitted.has(name)) throw new Error(`duplicate type name ${name}`);
  emitted.add(name);
  if (node.description) out.push(`/** ${node.description.replace(/\*\//g, "*\\/")} */`);
  if (node.properties) {
    out.push(`export interface ${name} ${objectBody(node, "")}`);
  } else {
    out.push(`export type ${name} = ${typeOf(node, "")};`);
  }
  out.push("");
}

function objectBody(node, indent) {
  const req = new Set(node.required || []);
  const lines = ["{"];
  for (const [key, prop] of Object.entries(node.properties)) {
    const opt = req.has(key) ? "" : "?";
    const doc = prop.description ? ` // ${prop.description.split("\n")[0]}` : "";
    lines.push(`${indent}  ${safeKey(key)}${opt}: ${typeOf(prop, indent + "  ")};${doc}`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}

function typeOf(node, indent) {
  if (node.$ref) return node.$ref.replace("#/$defs/", "");
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  const types = Array.isArray(node.type) ? node.type : [node.type];
  return types.map((t) => {
    switch (t) {
      case "number":
      case "integer":
        return "number";
      case "string":
        return "string";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `Array<${typeOf(node.items, indent)}>`;
      case "object":
        if (node.properties) return objectBody(node, indent);
        if (node.additionalProperties && typeof node.additionalProperties === "object") {
          return `Record<string, ${typeOf(node.additionalProperties, indent)}>`;
        }
        return "Record<string, unknown>";
      default:
        throw new Error(`unsupported schema type ${t}`);
    }
  }).join(" | ");
}

function safeKey(k) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== text) {
      console.error("types.generated.ts is out of date: run node scripts/gen-contract-types.mjs");
      process.exit(1);
    }
    console.log("types.generated.ts is up to date");
  } else {
    fs.writeFileSync(outFile, text);
    console.log(`wrote ${path.relative(root, outFile)}`);
  }
}
